    private fun applyLocale(context: Context, code: String) {
        runCatching {
            val targetLocale = if (code == "auto") {
                Locale.getDefault()
            } else {
                Locale.forLanguageTag(code)
            }

            Locale.setDefault(targetLocale)

            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
                val lm = context.getSystemService(LocaleManager::class.java)
                val list = if (code == "auto") LocaleList.getEmptyLocaleList() else LocaleList(targetLocale)
                lm?.applicationLocales = list
            }

            val resources = context.resources
            val config = resources.configuration
            config.setLocale(targetLocale)
            @Suppress("DEPRECATION")
            resources.updateConfiguration(config, resources.displayMetrics)

            // Configure NewPipe preferred localization & content country
            val hl = targetLocale.language.ifBlank { effectiveLanguageCode() }
            val gl = targetLocale.country.ifBlank { effectiveCountryCode() }
            val loc = Localization(hl, gl)
            val cc = ContentCountry(gl)
            NewPipe.setupLocalization(loc, cc)
            NewPipe.setPreferredLocalization(loc)
            NewPipe.setPreferredContentCountry(cc)

            // Modify YoutubeService.SUPPORTED_LANGUAGES via reflection so it doesn't reject preferred locale
            runCatching {
                val field = ServiceList.YouTube.javaClass.getDeclaredField("SUPPORTED_LANGUAGES")
                field.isAccessible = true
                val list = field.get(null)
                if (list is MutableList<*>) {
                    @Suppress("UNCHECKED_CAST")
                    val mList = list as MutableList<Localization>
                    if (!mList.contains(loc)) mList.add(loc)
                } else {
                    field.set(null, listOf(loc, Localization.DEFAULT))
                }
            }
        }
    }
